//! Embed walkthrough clips listed in assets/walkthrough/manifest.json.

#[path = "src/native_platform.rs"]
mod native_platform;

use std::env;
use std::fs;
use std::path::Path;

use serde::Deserialize;

#[derive(Deserialize)]
struct Manifest {
    #[serde(default)]
    clips: Vec<Clip>,
}

#[derive(Deserialize)]
struct Clip {
    step_id: String,
    path: String,
}

fn main() {
    println!("cargo:rustc-check-cfg=cfg(native_transport)");
    println!("cargo:rerun-if-changed=src/native_platform.rs");
    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let target = native_platform::TargetPlatform {
        os: &target_os,
        arch: &target_arch,
        pointer_width: env::var("CARGO_CFG_TARGET_POINTER_WIDTH")
            .ok()
            .and_then(|width| width.parse().ok())
            .unwrap_or(0),
        little_endian: env::var("CARGO_CFG_TARGET_ENDIAN").is_ok_and(|endian| endian == "little"),
        atomic64: env::var("CARGO_CFG_TARGET_HAS_ATOMIC")
            .is_ok_and(|widths| widths.split(',').any(|width| width == "64")),
    };
    if target.supports_native() {
        println!("cargo:rustc-cfg=native_transport");
    }
    let manifest = Path::new("assets/walkthrough/manifest.json");
    println!("cargo:rerun-if-changed={}", manifest.display());
    let text = fs::read_to_string(manifest).unwrap_or_else(|_| {
        r#"{"voice":"default","voice_id":"","model":"default","clips":[]}"#.into()
    });
    let parsed: Manifest = serde_json::from_str(&text).unwrap_or(Manifest { clips: Vec::new() });
    let mut out = String::from(
        "// @generated by build.rs from assets/walkthrough/manifest.json\n\
         pub static CLIPS: &[(&str, &[u8])] = &[\n",
    );
    for clip in parsed.clips {
        if clip.path.contains("..") || clip.path.contains('/') || clip.path.contains('\\') {
            continue;
        }
        let rel = format!("assets/walkthrough/{}", clip.path);
        println!("cargo:rerun-if-changed={rel}");
        out.push_str(&format!(
            "    ({:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/{rel}\"))),\n",
            clip.step_id
        ));
    }
    out.push_str("];\n");
    let dest = Path::new(&env::var("OUT_DIR").expect("OUT_DIR")).join("walkthrough_clips.rs");
    fs::write(dest, out).expect("write walkthrough_clips.rs");
    prismattyc_winres::embed(prismattyc_winres::file_description("prismattyc-host"));
}
